import { afterAll, beforeAll, expect, it } from 'vitest';
import http from 'node:http';
import { createHash } from 'node:crypto';
import type { AddressInfo } from 'node:net';
import { createApp } from '../../app';
import { closeDb, getDb } from '../../db';
import { createClient } from '../../dal/client.dal';
import { createProject } from '../../dal/project.dal';
import { createEvent } from '../../dal/event.dal';
import { buildBackup } from '../../services/backup.service';
let server:http.Server,base:string,input:Record<string,string>,target:string;
beforeAll(async()=>{
    process.env.E3_DB_PATH=':memory:';process.env.AUTH_MODE='local';process.env.PROJECT_PROMOTION_ENABLED='true';closeDb();
    const client=createClient({key:'promotion',name:'Synthetic'});
    const source=createProject({client_id:client.id,key:'same-key',name:'Source'}).id;
    createEvent(source,{name:'synthetic'});
    const raw=JSON.stringify(await buildBackup(source));
    getDb().prepare('DELETE FROM projects WHERE id=?').run(source);
    target=createProject({client_id:client.id,key:'same-key',name:'Existing target'}).id;
    input={source_project_id:source,destination_project_id:target,source_sha256:createHash('sha256').update(raw).digest('hex'),source_backup:raw};
    server=http.createServer(createApp());await new Promise<void>(resolve=>server.listen(0,'127.0.0.1',resolve));
    base=`http://127.0.0.1:${(server.address() as AddressInfo).port}`;
});
afterAll(async()=>{await new Promise<void>(resolve=>server.close(()=>resolve()));closeDb();for(const key of ['E3_DB_PATH','AUTH_MODE','PROJECT_PROMOTION_ENABLED'])delete process.env[key];});
const post=(path:string,body:unknown,origin:string|undefined=base)=>fetch(base+`/api/projects/${target}/promotion/`+path,{method:'POST',headers:{'Content-Type':'application/json',...(origin?{Origin:origin}:{})},body:JSON.stringify(body)});
it('requires an enabled, same-origin staff request and records verified actor instead of client input',async()=>{
    expect((await post('preview',{input},'https://evil.example')).status).toBe(403);
    expect((await post('preview',{input},'')).status).toBe(403);
    const preview=await post('preview',{input});expect(preview.status).toBe(200);const plan=await preview.json();
    expect(getDb().prepare('SELECT COUNT(*) n FROM events').get()).toEqual({n:0});
    const fields={input,plan_hash:plan.plan_hash,destination_baseline_hash:plan.destination_baseline_hash};
    expect((await post('apply',fields)).status).toBe(400);
    const applied=await post('apply',{...fields,human_confirmed:true,actor:'Forged approver'});expect(applied.status).toBe(200);
    const result=await applied.json();expect(result.actor).not.toBe('Forged approver');expect(JSON.stringify(result)).not.toContain('source_backup');
    expect((getDb().prepare('SELECT actor FROM change_log ORDER BY rowid DESC LIMIT 1').get() as {actor:string}).actor).toBe(result.actor);
    expect((await post('apply',{...fields,human_confirmed:true})).status).toBe(200);
    expect((await fetch(base+`/api/shared/not-a-token/promotion/preview`)).status).toBe(404);
    process.env.AUTH_MODE='remote';expect((await post('preview',{input})).status).toBe(401);process.env.AUTH_MODE='local';
    process.env.PROJECT_PROMOTION_ENABLED='false';expect((await post('preview',{input})).status).toBe(404);
});
