/**
 * Tiny deterministic PNG generator for the sandbox seed (T-4-11 part A): a mock "screenshot" with
 * coloured blocks and 5x7 bitmap text, so a trigger image is visibly something, not a 1x1
 * placeholder. No dependencies beyond node:zlib; same input gives the same bytes.
 */
import zlib from 'node:zlib';

// Classic 5x7 font, one byte per row, the low five bits are the pixels (bit 4 = leftmost).
